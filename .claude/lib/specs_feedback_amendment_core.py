def _tokens(text):
    return _TOKEN_RE.findall(text or "")


def _is_protected(tok):
    t = tok.lower()
    if any(ch.isdigit() for ch in t) or "_" in t:
        return True
    if _ID_TOKEN_RE.match(tok):
        return True
    if t in _PROTECTED_WORDS:
        return True
    if len(tok) == 1 and not tok.isalnum() and tok not in _PUNCT_OK:
        return True  # symbols: = < > + * / % $ & | # @ ^ ~ \ ...
    return False


def _osa(a, b):
    """Optimal-string-alignment (Damerau) distance."""
    a, b = a.lower(), b.lower()
    d = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(len(a) + 1):
        d[i][0] = i
    for j in range(len(b) + 1):
        d[0][j] = j
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            c = 0 if a[i - 1] == b[j - 1] else 1
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + c)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                d[i][j] = min(d[i][j], d[i - 2][j - 2] + 1)
    return d[len(a)][len(b)]


def _word_counts(text):
    counts = {}
    for w in re.findall(r"[A-Za-z]+", text or ""):
        counts[w.lower()] = counts.get(w.lower(), 0) + 1
    return counts


def prove_wording_only(before_line, after_line, baseline_text, entity_phrases=(),
                       equivalence=None):
    """(ok, reason). Deterministic proof that `after_line` differs from
    `before_line` by wording only. `baseline_text` is the WHOLE approved
    document (vocabulary evidence). `equivalence` = (P, Q) attested terminology
    equivalence or None."""
    if before_line == after_line:
        return False, "no change"
    tb, ta = _tokens(before_line), _tokens(after_line)
    sm = difflib.SequenceMatcher(a=tb, b=ta, autojunk=False)
    vocab = _word_counts(baseline_text)
    line_vocab = _word_counts(before_line)
    entities = {e.lower() for e in entity_phrases if e}
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        a_span, b_span = tb[i1:i2], ta[j1:j2]
        a_txt, b_txt = " ".join(a_span), " ".join(b_span)
        # pure punctuation / articles inserted or removed
        if all((t in _PUNCT_OK) or (t.lower() in _ARTICLES) for t in a_span + b_span):
            if tag in ("insert", "delete") or (
                    tag == "replace" and all((t in _PUNCT_OK) or t.lower() in _ARTICLES for t in a_span + b_span)):
                if tag == "replace" and any(t.lower() in _ARTICLES for t in a_span + b_span):
                    # article <-> article: case-only or a <-> an is grammar; a<->the is not
                    if not (len(a_span) == 1 and len(b_span) == 1
                            and (a_span[0].lower() == b_span[0].lower()
                                 or {a_span[0].lower(), b_span[0].lower()} == {"a", "an"})):
                        return False, "article replaced ('{}' -> '{}')".format(a_txt, b_txt)
                continue
        # declared terminology equivalence (whole differing span)
        if equivalence and a_txt == equivalence[0] and b_txt == equivalence[1]:
            if a_txt.lower() in entities or b_txt.lower() in entities:
                return False, "'{}'/'{}' is an actor/module name - renaming an entity is not wording".format(a_txt, b_txt)
            if any(_is_protected(t) for t in a_span + b_span):
                return False, "terminology equivalence touches protected tokens"
            others = baseline_text.replace(before_line, "")
            if not re.search(r"(?<![A-Za-z])" + re.escape(b_txt) + r"(?![A-Za-z])", others):
                return False, "'{}' is not already used elsewhere in the approved baseline".format(b_txt)
            continue
        if tag != "replace" or len(a_span) != len(b_span):
            return False, "words added/removed/rephrased ('{}' -> '{}')".format(a_txt, b_txt)
        for a, b in zip(a_span, b_span):
            if a == b:
                continue
            if a.lower() == b.lower():
                if _is_protected(a) and not any(ch.isdigit() for ch in a) and "_" in a:
                    return False, "protected token '{}' altered".format(a)
                continue  # capitalization only
            if _is_protected(a) or _is_protected(b):
                return False, "protected token changed ('{}' -> '{}')".format(a, b)
            if not (a.isalpha() and b.isalpha()):
                return False, "non-word replacement ('{}' -> '{}')".format(a, b)
            if a.lower() in entities or b.lower() in entities:
                return False, "entity name changed ('{}' -> '{}')".format(a, b)
            known = KNOWN_TYPOS.get(a.lower()) == b.lower()
            if not known:
                if len(a) < 4 or len(b) < 4:
                    return False, "'{}' -> '{}' is not a provable spelling fix".format(a, b)
                limit = 1 if max(len(a), len(b)) < 6 else 2
                if _osa(a, b) > limit:
                    return False, "'{}' -> '{}' differs by more than a typo".format(a, b)
                # a change in the word ending (plural / tense / agent: confirm ->
                # confirms, manager -> managed) can turn one real word into another;
                # only INTERIOR corrections are provable typo fixes.
                al, bl = a.lower(), b.lower()
                lcp = 0
                while lcp < min(len(al), len(bl)) and al[lcp] == bl[lcp]:
                    lcp += 1
                if lcp >= min(len(al), len(bl)) - 1:
                    return False, "'{}' -> '{}' changes the word ending, which can change meaning".format(a, b)
                misspelling_elsewhere = vocab.get(a.lower(), 0) - line_vocab.get(a.lower(), 0)
                if misspelling_elsewhere > 0 or line_vocab.get(a.lower(), 0) != vocab.get(a.lower(), 0):
                    return False, "'{}' is an existing word of the baseline, not a typo".format(a)
                if vocab.get(b.lower(), 0) < 1:
                    return False, "'{}' is not attested in the baseline".format(b)
    return True, None



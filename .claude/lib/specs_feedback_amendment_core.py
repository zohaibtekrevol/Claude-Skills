"""PMO FEEDBACK_AMENDMENT - deterministic core.

The one governed way an APPROVED Specs baseline may receive a
NON-SCOPE-CHANGING, NON-FUNCTIONAL correction that originates from a
canonical Feedback record, without a Change Request.

Three outcomes (never overlapping mutation mechanisms):

  NO_ARTIFACT_CHANGE       Feedback needs no Specs edit; the record is resolved,
                           Specs / approval / publication / version untouched.
  FEEDBACK_AMENDMENT       A wording-only correction, PROVEN structurally.
  CHANGE_REQUEST_REQUIRED  Anything else. Nothing is written, no CR is created.

Why this is safe (deterministic, not "the model says meaning is unchanged")
---------------------------------------------------------------------------
1. It starts only from a canonical Feedback Item already recorded in
   `docs/pmo/feedback/` (validated with feedback-governance-guard.py's own
   validators), classified, owned, evidenced, with the correction attested in
   the record's own text. A direct Specs edit followed by retroactive Feedback
   cannot satisfy this.
2. The candidate is GENERATED by this module from an exact before/after
   correction applied to ONE named target - never accepted as free-form text.
3. Only a closed set of line kinds may change (wording-eligible requirement
   fields, requirement titles, prose). Actors, Module, Source/Intent mappings,
   Permissions, Business Rules (fields AND table), Dependencies, integrations,
   status/applicability states, identifiers, every table and heading and the
   Document Control are PROTECTED: any change there is CHANGE_REQUEST_REQUIRED.
4. Inside an eligible line the change must pass `prove_wording_only`: the
   protected token sequence (numbers, identifiers, symbols, negations, modals,
   quantifiers, comparators) is identical, only capitalization / punctuation /
   articles / proven spelling fixes / declared terminology equivalence differ.
   Anything unprovable falls through to CHANGE_REQUEST_REQUIRED.
5. Terminology normalization is either a declared equivalence (P = Q, attested
   in the Feedback text, Q already used in the baseline, neither an actor or
   module name) or a UNIFORM RENAME of a term that is replaced everywhere
   (the whole document equals the original with P->Q, Q previously absent).
6. Versioning reuses the existing model (minor + 1, spec-generation Section
   10 / PMO-SPEC-007). Changed requirements get `Last Modified In` = the new
   version and `Change Source` = the Feedback Item id (Section 21.1); one new
   Change History row is appended. `Execution Authorized` becomes false: the
   amended bytes need a fresh PM approval through the existing recorder. The
   previous approval and the previous approved bytes are ARCHIVED (never
   altered); the previous publication receipt stays as history and can never
   satisfy the new version/hash (publication_evidence_core).

The transaction (`begin -> validate -> finalize`, `abort`) uses the same
marker pattern as the other Specs transactions; a failed amendment writes
nothing; finalize is all-or-nothing with rollback. Automatic progression:
never - approval and publication remain separate explicit actions.

Python 3, standard library only.
"""


def _item_fields(block):
    fields = {}
    for line in block.split("\n"):
        if line.strip().startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 3 and cells[0] not in ("Field", "---") and not set(cells[0]) <= set("-: "):
                fields[cells[0]] = cells[2]
    return fields


def load_feedback_record(root, item_id):
    """(record-dict, Decision-or-None). Validates the record with the Feedback
    guard's own validators; returns the parsed item plus its batch metadata."""
    if not fb_guard.ITEM_ID_RE.match(item_id or ""):
        return None, deny("PMO-FB-AMEND-001", "'{}' is not a canonical Feedback Item id (FB-YYYY-NNN-NNN).".format(item_id))
    batch_id = item_id.rsplit("-", 1)[0]
    bpath = os.path.join(root, "docs", "pmo", "feedback", "batches", batch_id + ".md")
    text = read_text(bpath)
    if text is None:
        return None, deny("PMO-FB-AMEND-001",
                          "no canonical Feedback record: {} does not exist - a Specs "
                          "amendment must start from a recorded Feedback item.".format(
                              "docs/pmo/feedback/batches/{}.md".format(batch_id)))
    d = fb_guard.validate_batch_content(text, root, batch_id)
    if d is not None and getattr(d, "decision", "deny") != "allow":
        code = getattr(d, "code", None)
        if code:
            return None, deny("PMO-FB-AMEND-002", "the Feedback batch is not valid ({}: {}).".format(code, d.message))
    blocks = dict(fb_guard.find_item_blocks(text))
    if item_id not in blocks:
        return None, deny("PMO-FB-AMEND-001", "Feedback item {} is not in batch {}.".format(item_id, batch_id))
    item = _item_fields(blocks[item_id])
    dc = fb_guard.field_map_from_table(*fb_guard.first_table(text))
    tracker = read_text(os.path.join(root, "docs", "pmo", "feedback", "feedback-tracker.md"))
    if tracker is None:
        return None, deny("PMO-FB-AMEND-002", "the Feedback Tracker does not exist.")
    td = fb_guard.validate_tracker_content(tracker, root)
    if td is not None and getattr(td, "code", None):
        return None, deny("PMO-FB-AMEND-002", "the Feedback Tracker is not valid ({}: {}).".format(td.code, td.message))
    th, trows = fb_guard.table_by_header_prefix(tracker, "Item ID")
    reg = [r for r in fb_guard.rows_as_dicts(th, trows) if r.get("Item ID", "").strip() == item_id]
    if not reg:
        return None, deny("PMO-FB-AMEND-002", "Feedback item {} is not registered in the Feedback Tracker.".format(item_id))
    return {"item_id": item_id, "batch_id": batch_id, "batch_path": bpath, "batch_text": text,
            "item": item, "batch_dc": dc, "tracker_row": reg[0]}, None


def validate_record_for_processing(rec, target_ref=None):
    """None or Decision. The record must be canonical, classified, owned,
    evidenced and still open."""
    it = rec["item"]
    for f in ("Original Feedback", "Normalized Interpretation", "Classification",
              "Classification Rationale", "Evidence / Source Reference", "Created Date",
              "Status", "Affected Artifact"):
        if not _clean(it.get(f)):
            return deny("PMO-FB-AMEND-003", "the Feedback item is missing required field '{}'.".format(f))
    if not _clean(rec["batch_dc"].get("Received By")) and not _clean(rec["batch_dc"].get("Created By")):
        return deny("PMO-FB-AMEND-003", "the Feedback batch has no PM ownership (Received By / Created By).")
    status = _clean(it["Status"]).upper()
    if status not in OPEN_ITEM_STATUSES:
        return deny("PMO-FB-AMEND-004", "Feedback item {} is already {} - it cannot start a new amendment.".format(rec["item_id"], status))
    if not re.search(r"spec", _clean(it["Affected Artifact"]), re.I):
        return deny("PMO-FB-AMEND-006", "Feedback item {} does not target the Specification (Affected Artifact: '{}').".format(rec["item_id"], it["Affected Artifact"]))
    return None


def _norm_ws(s):
    return re.sub(r"\s+", " ", s or "").strip().lower()


def _attested(rec, *phrases):
    """True when at least one of `phrases` appears in the record's own
    Original Feedback / Normalized Interpretation (evidence tie)."""
    hay = _norm_ws(rec["item"].get("Original Feedback", "") + " " + rec["item"].get("Normalized Interpretation", ""))
    return any(p and _norm_ws(p) in hay for p in phrases)



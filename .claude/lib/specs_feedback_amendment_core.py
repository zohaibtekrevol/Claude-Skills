# --------------------------------------------------------------------------- #
# NO_ARTIFACT_CHANGE resolution (independent of any Specs mutation)
# --------------------------------------------------------------------------- #

def resolve_without_change(root, item_id, reason):
    """(report, Decision|None). Resolves the Feedback record; Specs, approval,
    publication and version are not touched."""
    reason = _clean(reason)
    if not reason:
        return None, deny("PMO-FB-AMEND-014", "a reason is required.")
    res = build_candidate(root, item_id, None)
    if res.get("decision") is not None:
        return None, res["decision"]
    if res["outcome"] != NO_ARTIFACT_CHANGE:
        return None, deny("PMO-FB-AMEND-018", "the Feedback item is classified CHANGE_REQUEST and follows the Change Request lifecycle.")
    g = concurrency_gate(root)
    if g is not None:
        return None, g
    date_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    files, d = _close_feedback(root, res["record"], "Resolved with no Specs change: {}".format(reason), date_iso)
    if d is not None:
        return None, d
    _write_all(root, files)
    return {"feedback_item_id": item_id, "specs_changed": False}, None

def pm_message(result, engineering=False):
    o = result.get("outcome")
    if o == FEEDBACK_AMENDMENT:
        msg = ("Feedback identified as a non-functional baseline correction. It can be processed as a "
               "Feedback Amendment. No scope or functional behavior changes were detected. Once "
               "processed, the amended Specs will need your approval again before it is published.")
    elif o == NO_ARTIFACT_CHANGE:
        msg = ("This Feedback does not require any change to the Specs. It can be recorded as "
               "resolved; the approved baseline and its publication are unaffected.")
    elif o == CHANGE_REQUEST_REQUIRED:
        msg = ("This request changes more than wording - it would alter approved project content "
               "(" + "; ".join(result.get("reasons") or []) + "). It needs a Change Request. "
               "No change was made and no Change Request was created.")
    else:
        d = result.get("decision")
        msg = "This Feedback cannot be processed yet: " + (d.message if d else "unknown reason")
    if engineering:
        d = result.get("decision")
        msg += "\n[engineering] outcome={} reasons={} decision={}".format(
            o, result.get("reasons"), (d.code + ": " + d.message) if d else None)
    return msg



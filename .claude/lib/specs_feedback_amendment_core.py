def line_kinds(lines):
    """[kind] per line: DOC_CONTROL / HEADING / TABLE / BLOCK_TITLE /
    FIELD_TEXT:<label> / FIELD_PROTECTED:<label> / PROSE / BLANK / RULE."""
    kinds = []
    in_block = False
    in_dc = False
    label = None
    for line in lines:
        if not line.strip():
            kinds.append("BLANK"); label = None; continue
        if line.strip() == "---":
            kinds.append("RULE"); in_block = False; label = None; continue
        if _ANY_HEADING_RE.match(line):
            in_dc = bool(re.match(r"^#{1,6}\s+.*document control", line, re.I))
            if _BLOCK_HEADING_RE.match(line):
                in_block = True
                kinds.append("BLOCK_TITLE")
            else:
                in_block = False
                kinds.append("HEADING")
            label = None
            continue
        if line.lstrip().startswith("|"):
            kinds.append("TABLE"); continue
        if in_dc:
            kinds.append("DOC_CONTROL"); continue
        if in_block:
            m = _FIELD_LINE_RE.match(line)
            if m:
                label = m.group(1)
                kinds.append(("FIELD_TEXT:" if label in WORDING_LABELS else "FIELD_PROTECTED:") + label)
                continue
            if _LIST_ITEM_RE.match(line) and label:
                kinds.append(("FIELD_TEXT:" if label in WORDING_LABELS else "FIELD_PROTECTED:") + label)
                continue
            kinds.append("FIELD_PROTECTED:?")
            continue
        kinds.append("PROSE")
    return kinds


def entity_phrases(text):
    """Actor / module names and integration providers (protected terms)."""
    out = set()
    for m in re.finditer(r"(?m)^- \*\*Actor\(s\):\*\*[ \t]*(.+)$", text):
        for part in re.split(r",|\band\b", m.group(1)):
            p = part.strip().strip("*`")
            if p:
                out.add(p)
    for m in re.finditer(r"(?m)^- \*\*Module:\*\*[ \t]*(.+)$", text):
        val = m.group(1).strip().strip("*`")
        out.add(val)
        if "/" in val:
            out.add(val.rsplit("/", 1)[1].strip())
    return out


def blocks_of(lines):
    """[(start, end_exclusive, rid)] for FR/NFR blocks."""
    out, i = [], 0
    while i < len(lines):
        m = _BLOCK_HEADING_RE.match(lines[i])
        if m:
            j = i + 1
            while j < len(lines) and not _BLOCK_END_RE.match(lines[j]):
                j += 1
            out.append((i, j, m.group(1)))
            i = j
        else:
            i += 1
    return out



def next_minor(version):
    m = re.match(r"^(\d+)\.(\d+)$", _clean(version))
    if not m:
        return None
    return "{}.{}".format(m.group(1), int(m.group(2)) + 1)


def _cr(reason):
    return {"outcome": CHANGE_REQUEST_REQUIRED, "reasons": [reason], "candidate": None, "changed_ids": []}


def apply_correction(text, correction):
    """(candidate_text, changed_line_indexes, Decision-like reason | None).
    Pure. `correction` = {"kind": "text", "target": "FR-018", "before": "...",
    "after": "...", "equivalence": ["P", "Q"]|None} or {"kind": "rename",
    "from": "P", "to": "Q"}."""
    lines = text.split("\n")
    kinds = line_kinds(lines)
    kind = correction.get("kind")
    if kind == "rename":
        p, q = correction.get("from"), correction.get("to")
        if not p or not q or p == q:
            return None, [], "a rename needs two different terms"
        rx = re.compile(r"(?<![A-Za-z0-9])" + re.escape(p) + r"(?![A-Za-z0-9])")
        if re.search(r"(?<![A-Za-z0-9])" + re.escape(q) + r"(?![A-Za-z0-9])", text):
            return None, [], "SUBSTANTIVE: '{}' already exists in the baseline - the rename would merge two terms".format(q)
        changed = []
        new = list(lines)
        for i, l in enumerate(lines):
            if rx.search(l):
                if kinds[i] in ("DOC_CONTROL", "HEADING"):
                    return None, [], "SUBSTANTIVE: '{}' occurs in a protected line ({})".format(p, kinds[i])
                if kinds[i] == "BLOCK_TITLE" or kinds[i] == "TABLE" or kinds[i] == "PROSE" \
                        or kinds[i].startswith(("FIELD_TEXT", "FIELD_PROTECTED")):
                    # identifiers can never be renamed
                    if _ID_TOKEN_RE.match(p):
                        return None, [], "SUBSTANTIVE: identifiers cannot be renamed"
                    new[i] = rx.sub(q, l)
                    changed.append(i)
        if not changed:
            return None, [], "'{}' does not occur in the baseline".format(p)
        return "\n".join(new), changed, None
    if kind != "text":
        return None, [], "unknown correction kind"
    target, before, after = correction.get("target"), correction.get("before"), correction.get("after")
    if not target or not before or after is None or before == after:
        return None, [], "a text correction needs a target, a 'before' and a different 'after'"
    if "\n" in before or "\n" in after:
        return None, [], "SUBSTANTIVE: a correction spanning several lines adds or removes content"
    if re.match(r"^(?:FR|NFR)-\d+$", target):
        rng = [(s, e) for s, e, rid in blocks_of(lines) if rid == target]
        if not rng:
            return None, [], "target {} does not exist".format(target)
        lo, hi = rng[0]
    elif target.startswith("section:"):
        name = target[len("section:"):].strip().lower()
        lo = hi = None
        for i, l in enumerate(lines):
            if _ANY_HEADING_RE.match(l) and name in l.lower():
                lo = i + 1
                hi = i + 1
                while hi < len(lines) and not _ANY_HEADING_RE.match(lines[hi]):
                    hi += 1
                break
        if lo is None:
            return None, [], "section '{}' does not exist".format(name)
    else:
        return None, [], "target must be a requirement id (FR-nnn / NFR-nnn) or 'section:<heading>'"
    hits = [i for i in range(lo, hi) if before in lines[i]]
    total = sum(lines[i].count(before) for i in hits)
    if total != 1:
        return None, [], "the 'before' text occurs {} times in {} (must be exactly once)".format(total, target)
    i = hits[0]
    new = list(lines)
    new[i] = lines[i].replace(before, after, 1)
    return "\n".join(new), [i], None


def classify_candidate(before_text, candidate, changed_idx, correction, rec_attested_equivalence=True):
    """(outcome, reasons). Every changed line must be an amendable kind AND
    pass the wording proof (text) / be a pure term substitution (rename)."""
    blines = before_text.split("\n")
    alines = candidate.split("\n")
    if len(blines) != len(alines):
        return CHANGE_REQUEST_REQUIRED, ["the correction changes the document structure"]
    kinds = line_kinds(blines)
    ents = entity_phrases(before_text)
    reasons = []
    if correction.get("kind") == "rename":
        p, q = correction["from"], correction["to"]
        rx = re.compile(r"(?<![A-Za-z0-9])" + re.escape(p) + r"(?![A-Za-z0-9])")
        if rx.search(candidate):
            return CHANGE_REQUEST_REQUIRED, ["'{}' would remain in the baseline - not a uniform rename".format(p)]
        if candidate != "\n".join(rx.sub(q, l) for l in blines):
            return CHANGE_REQUEST_REQUIRED, ["the rename is not a pure substitution"]
        if any(t.isdigit() or "_" in t or _ID_TOKEN_RE.match(t) or t.lower() in _PROTECTED_WORDS
               or (len(t) == 1 and not t.isalnum() and t not in _PUNCT_OK) for t in _tokens(p) + _tokens(q)):
            return CHANGE_REQUEST_REQUIRED, ["a rename cannot involve numbers, identifiers or logic words"]
        return FEEDBACK_AMENDMENT, ["uniform terminology rename '{}' -> '{}' ({} line(s))".format(p, q, len(changed_idx))]
    eq = correction.get("equivalence")
    eq = tuple(eq) if eq else None
    for i in changed_idx:
        k = kinds[i]
        if k in ("BLOCK_TITLE",):
            m1, m2 = _BLOCK_HEADING_RE.match(blines[i]), _BLOCK_HEADING_RE.match(alines[i])
            if not (m1 and m2 and m1.group(1) == m2.group(1)):
                return CHANGE_REQUEST_REQUIRED, ["the requirement identifier in a heading would change"]
            ok, why = prove_wording_only(m1.group(2), m2.group(2), before_text, ents, eq)
        elif k.startswith("FIELD_TEXT:") or k == "PROSE":
            ok, why = prove_wording_only(blines[i], alines[i], before_text, ents, eq)
        else:
            return CHANGE_REQUEST_REQUIRED, [
                "the change touches a protected part of the baseline ({}) - "
                "requirements, actors, mappings, rules, tables and headings cannot be "
                "changed by Feedback".format(k.replace("FIELD_PROTECTED:", "field '").rstrip() + ("'" if k.startswith("FIELD_PROTECTED:") else ""))]
        if not ok:
            return CHANGE_REQUEST_REQUIRED, [why]
        reasons.append("wording-only: " + (correction.get("before") or ""))
    return FEEDBACK_AMENDMENT, reasons or ["wording-only correction"]


def stamp_candidate(candidate, before_text, changed_idx, item_id, old_version, new_version, date_iso, summary):
    """Governed metadata for a successful amendment: version, execution
    authorization, per-changed-requirement Last Modified In / Change Source,
    one Change History row. Returns (text, changed_requirement_ids)."""
    lines = candidate.split("\n")
    blocks = blocks_of(lines)
    changed_ids = []
    for s, e, rid in blocks:
        if any(s <= i < e for i in changed_idx):
            changed_ids.append(rid)
            for j in range(s, e):
                m = _FIELD_LINE_RE.match(lines[j])
                if m and m.group(1) == "Last Modified In":
                    lines[j] = "- **Last Modified In:** {}".format(new_version)
                elif m and m.group(1) == "Change Source":
                    lines[j] = "- **Change Source:** {}".format(item_id)
    text = "\n".join(lines)
    text, ok1 = iac.set_doc_control_field(text, "Spec Version", new_version)
    text, ok2 = iac.set_doc_control_field(text, "Execution Authorized", "false") if ok1 else (None, False)
    if not (ok1 and ok2):
        return None, []
    ids = ", ".join(changed_ids) if changed_ids else "(document text)"
    row = "| {} | {} | {} | {} | {} | Pending PM approval (Feedback amendment) |".format(
        new_version, date_iso, item_id, ids, summary)
    out = text.rstrip("\n").split("\n")
    # append the row directly after the last row of the Change History table
    hm = [i for i, l in enumerate(out) if re.match(r"^#{1,6}\s+.*specification change history", l, re.I)]
    if not hm:
        return None, []
    i = hm[0] + 1
    while i < len(out) and not out[i].strip().startswith("|"):
        i += 1
    while i < len(out) and out[i].strip().startswith("|"):
        i += 1
    out.insert(i, row)
    return "\n".join(out) + "\n", changed_ids


def build_candidate(root, item_id, correction):
    """The single deterministic classification + candidate pipeline.
    Read-only. Returns a dict {outcome, reasons, candidate, changed_ids,
    version_before, version_after, record}."""
    rec, d = load_feedback_record(root, item_id)
    if d is not None:
        return {"outcome": None, "decision": d}
    d = validate_record_for_processing(rec)
    if d is not None:
        return {"outcome": None, "decision": d}
    cls = _clean(rec["item"]["Classification"]).upper()
    linked_cr = _clean(rec["item"].get("Related CR"))
    if linked_cr and linked_cr.lower() not in ("none", "n/a", "-"):
        r = _cr("the Feedback item is linked to Change Request {} - it follows the Change Request lifecycle".format(linked_cr))
        r["record"] = rec
        return r
    if not correction:
        if cls == "CHANGE_REQUEST":
            r = _cr("the Feedback item is classified CHANGE_REQUEST")
            r["record"] = rec
            return r
        return {"outcome": NO_ARTIFACT_CHANGE, "reasons": ["the Feedback needs no Specs change"],
                "candidate": None, "changed_ids": [], "record": rec}
    if cls == "CHANGE_REQUEST":
        r = _cr("the Feedback item is classified CHANGE_REQUEST - it follows the Change Request lifecycle")
        r["record"] = rec
        return r
    if cls in NO_CHANGE_CLASSIFICATIONS:
        return {"outcome": NO_ARTIFACT_CHANGE,
                "reasons": ["the Feedback is classified {} and asks for no Specs change".format(cls)],
                "candidate": None, "changed_ids": [], "record": rec}
    if cls not in AMENDABLE_CLASSIFICATIONS:
        r = _cr("Feedback classification '{}' is not amendable".format(cls)); r["record"] = rec
        return r

    specs_text = read_text(src.specs_abspath(root))
    if specs_text is None:
        return {"outcome": None, "decision": deny("PMO-FB-AMEND-007", "no canonical Specs artifact.")}
    meta = sac.parse_spec_doc_control(specs_text)
    version_before = _clean(meta.get("spec_version"))
    version_after = next_minor(version_before)
    if version_after is None:
        return {"outcome": None, "decision": deny("PMO-FB-AMEND-007", "Spec Version '{}' cannot be advanced by the existing minor+1 rule.".format(version_before))}

    # evidence tie: the correction must be attested by the Feedback record itself
    phrases = [correction.get("before"), correction.get("after"), correction.get("from"), correction.get("to")]
    if not _attested(rec, *phrases):
        return {"outcome": None, "decision": deny(
            "PMO-FB-AMEND-008",
            "the requested correction is not attested by the Feedback record's own text "
            "(Original Feedback / Normalized Interpretation) - a Specs edit cannot precede its Feedback.")}
    if correction.get("kind") == "text":
        tgt = correction.get("target") or ""
        affected = _clean(rec["item"].get("Affected Existing Requirement IDs"))
        if re.match(r"^(?:FR|NFR)-\d+$", tgt) and tgt not in affected:
            return {"outcome": None, "decision": deny(
                "PMO-FB-AMEND-009",
                "the correction targets {} but the Feedback item's Affected Existing Requirement IDs "
                "('{}') do not include it.".format(tgt, affected or "none"))}
    eq = correction.get("equivalence")
    if eq and not _attested(rec, eq[0], eq[1]):
        return {"outcome": None, "decision": deny(
            "PMO-FB-AMEND-008", "the terminology equivalence is not attested by the Feedback record.")}

    candidate, changed_idx, why = apply_correction(specs_text, correction)
    if candidate is None and (why or "").startswith("SUBSTANTIVE:"):
        return {"outcome": CHANGE_REQUEST_REQUIRED, "reasons": [why[len("SUBSTANTIVE:"):].strip()],
                "candidate": None, "changed_ids": [], "record": rec, "version_before": version_before}
    if candidate is None:
        return {"outcome": None, "decision": deny("PMO-FB-AMEND-010", "the correction cannot be applied deterministically: {}.".format(why))}
    outcome, reasons = classify_candidate(specs_text, candidate, changed_idx, correction)
    if outcome != FEEDBACK_AMENDMENT:
        return {"outcome": CHANGE_REQUEST_REQUIRED, "reasons": reasons, "candidate": None,
                "changed_ids": [], "record": rec, "version_before": version_before}
    summary = "Feedback amendment (wording only, no functional change): {}".format(
        _summary_of(correction))
    stamped, changed_ids = stamp_candidate(candidate, specs_text, changed_idx, item_id,
                                           version_before, version_after,
                                           datetime.now(timezone.utc).strftime("%Y-%m-%d"), summary)
    if stamped is None:
        return {"outcome": None, "decision": deny("PMO-FB-AMEND-011", "the governed metadata could not be located deterministically.")}
    return {"outcome": FEEDBACK_AMENDMENT, "reasons": reasons, "candidate": stamped,
            "changed_ids": changed_ids, "record": rec, "version_before": version_before,
            "version_after": version_after, "correction_line_indexes": changed_idx}


def _summary_of(c):
    if c.get("kind") == "rename":
        return "terminology '{}' -> '{}'".format(c["from"], c["to"])
    return "'{}' -> '{}' in {}".format(c["before"], c["after"], c["target"])



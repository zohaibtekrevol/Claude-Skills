def parse_marker(text):
    try:
        data = json.loads(text)
    except Exception as exc:
        return None, "marker is not valid JSON: {}".format(exc)
    if not isinstance(data, dict):
        return None, "marker did not parse to an object."
    missing = [f for f in MARKER_REQUIRED_FIELDS if f not in data]
    if missing:
        return data, "marker is missing field(s): {}.".format(", ".join(missing))
    if data.get("transaction_type") != TRANSACTION_TYPE or data.get("operation") != OPERATION:
        return data, "marker is not a {} transaction.".format(OPERATION)
    if data.get("status") not in OPEN_STATUSES:
        return data, "marker status '{}' is not a recognised open state.".format(data.get("status"))
    return data, None


def marker_status(root):
    text = read_text(marker_abspath(root))
    if text is None:
        return "ABSENT", None, None
    data, err = parse_marker(text)
    if err is not None:
        return "INVALID", data, err
    cfg = src.load_project_config(root) or {}
    pid = _clean((cfg.get("project") or {}).get("id"))
    if pid and _clean(data.get("project_id")).upper() != pid.upper():
        return "WRONG_PROJECT", data, "marker project_id does not match project-config.yaml."
    return "OPEN", data, None


def approved_baseline_gate(root, specs_text):
    """None when the current Specs is a valid, approved baseline whose approval
    matches (the only state an amendment applies to)."""
    d = specs_guard.full_spec_validation(root, spec_text=specs_text)
    if d is not None:
        return deny("PMO-FB-AMEND-012", "the current Specs is not clean ({}: {}).".format(d.code, d.message))
    meta = sac.parse_spec_doc_control(specs_text)
    if _clean(meta.get("execution_authorized")).lower() != "true":
        return deny("PMO-FB-AMEND-012", "the Specs is not an approved baseline (Execution Authorized is not true) - pre-approval fixes use the pre-baseline mechanisms.")
    data, err = sac.load_specs_approval(root)
    if data is None or err is not None:
        return deny("PMO-FB-AMEND-012", "no valid Specs approval record: {}".format(err))
    err = sac.validate_specs_approval_matches(root, spec_version=meta.get("spec_version"))
    if err is not None:
        return deny("PMO-FB-AMEND-012", err)
    return None


def concurrency_gate(root):
    if crc.cr_marker_status(root)[0] == "OPEN":
        return deny("PMO-FB-AMEND-013", "a Change Request transaction is open.")
    if crc.feedback_marker_is_open(root):
        return deny("PMO-FB-AMEND-013", "a Feedback-management transaction is open.")
    for parts, name in ((src.STRUCTURAL_REPAIR_MARKER_RELPATH_PARTS, "structural repair"),
                        (src.SCHEMA_MIGRATION_MARKER_RELPATH_PARTS, "schema migration"),
                        ((".pmo", "specs-approval-transaction.json"), "Specs approval")):
        if os.path.exists(os.path.join(root, *parts)):
            return deny("PMO-FB-AMEND-013", "a {} transaction marker exists.".format(name))
    return None


def plan_transaction(root, item_id, correction, reason):
    """(plan, Decision|None, classification-result). Read-only."""
    reason = _clean(reason)
    if not reason:
        return None, deny("PMO-FB-AMEND-014", "a processing reason (PM approval to process) is required."), None
    specs_text = read_text(src.specs_abspath(root))
    if specs_text is None:
        return None, deny("PMO-FB-AMEND-007", "no canonical Specs artifact."), None
    g = approved_baseline_gate(root, specs_text)
    if g is not None:
        return None, g, None
    g = concurrency_gate(root)
    if g is not None:
        return None, g, None
    res = build_candidate(root, item_id, correction)
    if res.get("decision") is not None:
        return None, res["decision"], res
    if res["outcome"] != FEEDBACK_AMENDMENT:
        return None, None, res
    dv = specs_guard.full_spec_validation(root, spec_text=res["candidate"])
    if dv is not None:
        return None, deny("PMO-FB-AMEND-015",
                          "the amended Specs would fail validation ({}: {}) - nothing written.".format(dv.code, dv.message)), res
    cfg = src.load_project_config(root) or {}
    plan = {
        "project_id": _clean((cfg.get("project") or {}).get("id")),
        "feedback_item_id": item_id, "correction": correction, "reason": reason,
        "spec_version_before": res["version_before"], "spec_version_after": res["version_after"],
        "specs_hash_before": src.sha256_of_text(specs_text), "changed_ids": res["changed_ids"],
    }
    return plan, None, res


